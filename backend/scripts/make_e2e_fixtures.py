"""Write the synthetic before/after GeoTIFF pair used by the browser acceptance test.

    python scripts/make_e2e_fixtures.py <output-dir>

The scenes are synthetic (known ground-truth change), generated by the same code the unit tests use.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.geo.synthetic import make_synthetic_pair  # noqa: E402


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    pair = make_synthetic_pair(out)
    print(pair.before)
    print(pair.after)


if __name__ == "__main__":
    main()
